import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import type { ResolvedContract, ResolvedRule } from "./resolve.js";

export const MARK_START = "<!-- fcs:start -->";
export const MARK_END = "<!-- fcs:end -->";
export const COMPONENTS_DIR = "components/fcs";
export const GENERATED_PARAMS_FILE = `${COMPONENTS_DIR}/contract.generated.ts`;

export interface GeneratedFile {
  /** Path relative to project root. */
  file: string;
  /** `region` = only the marked block is owned; `whole` = the entire file is owned. */
  mode: "region" | "whole";
  content: string;
}

const AREA_TITLES: Record<string, string> = {
  forms: "Forms",
  loading: "Loading states",
  layout: "Layout",
  feedback: "Feedback",
  a11y: "Accessibility",
  motion: "Motion",
  tokens: "Tokens",
};

function areaOf(id: string): string {
  return id.split(".")[0]!;
}

function fence(code: string): string {
  return ["```tsx", code.trimEnd(), "```"].join("\n");
}

function renderRule(rule: ResolvedRule, scopes: ResolvedContract["scopes"]): string {
  const lines: string[] = [`#### \`${rule.id}\` — ${rule.title}${rule.severity === "warn" ? " _(warning)_" : ""}`];
  const meta: string[] = [];
  if (rule.enforce?.component) meta.push(`**Use:** \`${rule.enforce.component}\``);
  const params = Object.entries(rule.params);
  if (params.length) meta.push(`**Params:** ${params.map(([k, v]) => `\`${k}=${String(v)}\``).join(", ")}`);
  if (rule.scope?.length) {
    meta.push(`**Applies to:** ${rule.scope.map((s) => scopes[s]?.include.map((g) => `\`${g}\``).join(", ") ?? s).join(", ")}`);
  }
  if (rule.exceptions.length) {
    meta.push(`**Except:** ${rule.exceptions.map((e) => `\`${e.path}\` (${e.reason})`).join(", ")}`);
  }
  if (meta.length) lines.push(meta.join(" · "));
  lines.push("", `**Why:** ${rule.why.trim()}`);
  if (rule.do) lines.push("", "Do:", fence(rule.do));
  if (rule.dont) lines.push("", "Don't:", fence(rule.dont));
  return lines.join("\n");
}

/** Markdown body shared by every agent instruction file. */
export function renderRulesMarkdown(resolved: ResolvedContract): string {
  const active = resolved.rules.filter((r) => r.severity !== "off");
  const byArea = new Map<string, ResolvedRule[]>();
  for (const r of active) {
    const list = byArea.get(areaOf(r.id)) ?? [];
    list.push(r);
    byArea.set(areaOf(r.id), list);
  }

  const out: string[] = [
    "## UI contract (frontend-consistency)",
    "",
    "_Generated by `fcs build` from `.design/` — do not edit this block; change `.design/` and rebuild._",
    "",
    "These rules are enforced by lint after every edit. When a rule names a component, use that component — do not re-implement it.",
    "",
    `- Never edit files under \`${COMPONENTS_DIR}/\`; they are locked. Change behaviour through \`.design/\` params.`,
    "- Never disable `fcs/*` lint rules (no `eslint-disable`). If a rule seems wrong for this case, stop and ask.",
    "- Run `fcs check` before declaring UI work done.",
  ];
  for (const [area, rules] of byArea) {
    out.push("", `### ${AREA_TITLES[area] ?? area}`);
    for (const r of rules) out.push("", renderRule(r, resolved.scopes));
  }
  return out.join("\n");
}

export function renderParamsModule(resolved: ResolvedContract): string {
  const rules = Object.fromEntries(
    resolved.rules.map((r) => [r.id, { severity: r.severity, params: r.params }]),
  );
  return [
    "// Generated by `fcs build` from .design/ — do not edit.",
    "",
    `export const fcsRules = ${JSON.stringify(rules, null, 2)} as const;`,
    "",
    `export const fcsParams = ${JSON.stringify(resolved.params, null, 2)} as const;`,
    "",
    "export type FcsRuleId = keyof typeof fcsRules;",
    "",
    "/** Params of a rule, or undefined when the rule is off. */",
    "export function ruleParams<Id extends FcsRuleId>(id: Id): (typeof fcsRules)[Id][\"params\"] | undefined {",
    "  const rule = fcsRules[id];",
    "  return (rule.severity as string) === \"off\" ? undefined : rule.params;",
    "}",
    "",
  ].join("\n");
}

export interface GenerateOptions {
  /** Emit `.cursor/rules/fcs.mdc` (default: when `.cursor/` exists). */
  cursor?: boolean;
}

export function generateFiles(resolved: ResolvedContract, root: string, opts: GenerateOptions = {}): GeneratedFile[] {
  const md = renderRulesMarkdown(resolved);
  const files: GeneratedFile[] = [
    { file: "AGENTS.md", mode: "region", content: md },
    { file: "CLAUDE.md", mode: "region", content: md },
    { file: "DESIGN.md", mode: "region", content: md },
    { file: GENERATED_PARAMS_FILE, mode: "whole", content: renderParamsModule(resolved) },
  ];
  if (opts.cursor ?? existsSync(path.join(root, ".cursor"))) {
    files.push({
      file: ".cursor/rules/fcs.mdc",
      mode: "whole",
      content: ["---", "description: UI contract enforced by frontend-consistency", "alwaysApply: true", "---", "", md, ""].join("\n"),
    });
  }
  return files;
}

/** Replace (or append) the marked region, leaving everything else untouched. */
export function upsertRegion(existing: string, body: string): string {
  const block = `${MARK_START}\n${body.trimEnd()}\n${MARK_END}`;
  const start = existing.indexOf(MARK_START);
  const end = existing.indexOf(MARK_END);
  if (start !== -1 && end > start) {
    return existing.slice(0, start) + block + existing.slice(end + MARK_END.length);
  }
  if (!existing.trim()) return `${block}\n`;
  return `${existing.trimEnd()}\n\n${block}\n`;
}

export interface WriteResult {
  file: string;
  changed: boolean;
}

/**
 * Write generated files. With `dryRun`, nothing is written — use `changed` to detect a stale build (CI).
 */
export function writeGenerated(files: GeneratedFile[], root: string, { dryRun = false } = {}): WriteResult[] {
  return files.map(({ file, mode, content }) => {
    const abs = path.join(root, file);
    const existing = existsSync(abs) ? readFileSync(abs, "utf8") : "";
    const next = mode === "region" ? upsertRegion(existing, content) : content;
    const changed = next !== existing;
    if (changed && !dryRun) {
      mkdirSync(path.dirname(abs), { recursive: true });
      writeFileSync(abs, next);
    }
    return { file, changed };
  });
}
